"""Summaries and the LaTeX table of the ten-player NBA experiment (offense and defense, k=10)."""
import argparse
import collections
import csv
import json
from pathlib import Path

import numpy as np

METHODS = (("blocking", "Blocking"), ("probe_all", "Probe-all"), ("store_all", "Store-all"),
           ("per_curve-intersection", "Intersection"))


def per_seed(folder):
    """{display_method: summary} for one seed folder, computed from the per-query rows."""
    main = json.loads((folder / "main-results.json").read_text())
    evaluated = json.loads((folder / "evaluated-configurations.json").read_text())
    rows = collections.defaultdict(list)
    with (folder / "test-queries.csv").open() as handle:
        for row in csv.DictReader(handle):
            rows[row["config_id"]].append(row)
    out = {}
    for entry in main:
        method, config = entry["display_method"], entry.get("config_id")
        if method not in dict(METHODS):
            continue
        if config is None or entry.get("test_status") != "complete":
            out[method] = dict(status=entry.get("test_status"))
            continue
        R = rows[config]
        seconds = np.array([float(r["seconds"]) for r in R])
        ids = np.array([int(r["id"]) for r in R])
        distance = np.array([float(r["distance"]) for r in R])
        optimum = np.array([float(r["nn_distance"]) for r in R])
        exact = (ids >= 0) & (np.abs(distance - optimum) <= 1e-9)
        out[method] = dict(
            status="complete", config=config, blocks=entry.get("blocks"), delta=entry.get("delta"), L=entry.get("L"),
            median_ms=1000 * float(np.median(seconds)), p95_ms=1000 * float(np.percentile(seconds, 95)),
            index_mb=evaluated[config]["index_bytes"] / 2 ** 20, recall=float(exact.mean()),
            candidates=float(np.mean([float(r["candidates"]) for r in R])),
            verified=float(np.mean([float(r["verified"]) for r in R])),
            probes=float(np.mean([float(r["probes"]) for r in R])),
            timeouts=sum(r["timeout"] == "True" for r in R), queries=len(R))
    return out


def load(results):
    seeds = sorted(Path(results).glob("nba-both-k10-seed*"))
    seeds = [s for s in seeds if (s / "main-results.json").is_file() and (s / "test-queries.csv").is_file()]
    return {s.name: per_seed(s) for s in seeds}


def aggregate(data):
    table = {}
    for method, _ in METHODS:
        runs = [d[method] for d in data.values() if method in d]
        done = [r for r in runs if r["status"] == "complete"]
        if len(done) != len(runs) or not done:
            table[method] = dict(status=runs[0]["status"] if runs else "missing")
            continue
        table[method] = dict(
            status="complete", seeds=len(done),
            median_ms=float(np.median([r["median_ms"] for r in done])),
            index_mb=float(np.median([r["index_mb"] for r in done])),
            recall=float(np.mean([r["recall"] for r in done])),
            candidates=float(np.mean([r["candidates"] for r in done])),
            verified=float(np.mean([r["verified"] for r in done])),
            configs=sorted({f"{'+'.join(map(str, r['blocks']))}@{int(r['delta'])}/L{r['L']}" if r["blocks"]
                            else f"@{int(r['delta'])}/L{r['L']}" for r in done}))
    return table


def latex(table):
    rows = []
    for method, label in METHODS:
        t = table[method]
        if t["status"] != "complete":
            rows.append(f"{label} & \\multicolumn{{4}}{{c}}{{not built ($10!$ stored orders per play)}}\\\\")
            continue
        candidates = f"{t['candidates']:,.0f}".replace(",", "{,}")
        rows.append(f"{label} & {t['median_ms']:.2f} & {t['index_mb']:.1f} & {100 * t['recall']:.1f} & {candidates}" + "\\\\")
    return "\n".join([r"\begin{tabular}{lrrrr}", r"\toprule",
                      r"Method & Latency (ms) & Index (MB) & Recall@1 (\%) & Candidates\\", r"\midrule", *rows,
                      r"\bottomrule", r"\end{tabular}"]) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", default="results/nba-both-k10-20261016")
    parser.add_argument("--table")
    args = parser.parse_args()
    data = load(args.results)
    for seed, summary in data.items():
        print(seed, {m: (round(v["median_ms"], 3), round(v["index_mb"], 1), round(v["recall"], 3)) if v["status"] == "complete"
                     else v["status"] for m, v in summary.items()})
    table = aggregate(data)
    print(json.dumps(table, indent=1))
    if args.table:
        Path(args.table).write_text("% Generated by fresh.nba_both_report.\n" + latex(table))


if __name__ == "__main__":
    main()
